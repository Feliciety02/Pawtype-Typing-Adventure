// PawType Typing Curriculum
// 13 units, each with a series of lessons. Every lesson carries a curated
// word/sentence bank that TypingArena can consume via customWords.

export type LessonDifficulty =
  "beginner" | "easy" | "intermediate" | "advanced" | "expert" | "master";

export type Lesson = {
  id: string;
  title: string;
  emoji: string;
  difficulty: LessonDifficulty;
  targetWpm: number;
  targetAccuracy: number;
  words: string[];
  note?: string;
};

export type Unit = {
  id: string;
  number: number;
  title: string;
  emoji: string;
  purpose: string;
  lessons: Lesson[];
};

// ---------- helpers ----------
const rep = (arr: string[], times: number): string[] => {
  const out: string[] = [];
  for (let i = 0; i < times; i++) out.push(...arr);
  return out;
};

const mix = (...groups: string[][]): string[] => {
  const out: string[] = [];
  const max = Math.max(...groups.map((g) => g.length));
  for (let i = 0; i < max; i++) {
    for (const g of groups) if (g[i]) out.push(g[i]);
  }
  return out;
};

const drill = (letters: string[], count = 8): string[] => letters.map((l) => l.repeat(count));

